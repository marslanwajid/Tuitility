export function getDecorationSymbols(path: string, category: string): { text: string; className: string }[] {
  const exact = EXACT_TOOL_DECORATIONS[path];
  if (exact) return exact.symbols;
  return categoryFallbackSymbols[category.toLowerCase()] || [];
}

export function getDecorationPositions(): string[] {
  return positions;
}

